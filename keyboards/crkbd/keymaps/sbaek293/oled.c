oled_rotation_t oled_init_user(oled_rotation_t rotation) {
    if (!is_keyboard_master()) {
        return OLED_ROTATION_0;  /* slave: landscape for official corne logo */
    }
    return OLED_ROTATION_270;   /* master: portrait (PandaKBLab style)       */
}

